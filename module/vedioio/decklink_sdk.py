"""DeckLink input through the Desktop Video COM API (no ffmpeg), with the SDI ancillary
packets of every frame.

ffmpeg's decklink input drops the VANC packets, so lens metadata carried in the SDI
(Sony HDCU-5500: DID 0x51 SDID 0x01) is only reachable here. Video and packets come from
the same SDI frame, so the zoom value matches the picture exactly (no delay tuning).

    reader = DeckLinkSDKReader(device="0")      # index or part of the name
    ok, bgr = reader.read()                     # frame k (k = 0, 1, 2 ... in read order)
    reader.packets_for(k)                       # [(did, sdid, line, bytes), ...] of that frame

Interlaced signals (1080i) are delivered one picture per SDI frame: "adaptive" (default)
keeps both fields (full 1080 lines) where the picture is still and rebuilds the second field
from the first only where it moved since the last frame (no combing); "bob" uses the first
field only (540 lines doubled); "weave" keeps both fields as they are.
Colors use BT.709 (HD), not OpenCV's BT.601 default.
The device is exclusive: OBS / Media Express must not use the same input at the same time.
"""
from __future__ import annotations

import ctypes
import queue
import sys
import threading
from collections import OrderedDict
from typing import Optional

import cv2
import numpy as np

DECKLINK_TLB = ("{D864517A-EDD5-466D-867D-C819F1C052BB}", 1, 0)


def _bt709_affine() -> np.ndarray:
    """(Y, Cb, Cr) limited range -> (B, G, R), BT.709, as a 3x4 matrix for cv2.transform
    (cv2.cvtColor's UYVY decode is BT.601, which shifts HD colors)."""
    a = np.array([[1.164, 2.112, 0.0],       # B
                  [1.164, -0.213, -0.533],   # G
                  [1.164, 0.0, 1.793]])      # R
    return np.hstack([a, -(a @ np.array([[16.0], [128.0], [128.0]]))]).astype(np.float32)


BT709_UYVY = _bt709_affine()


def uyvy_to_bgr709(uyvy: np.ndarray) -> np.ndarray:
    """UYVY bytes (H, 2W) -> BGR (H, W) with BT.709, chroma interpolated horizontally.
    One affine step in float: no clipping between steps."""
    h, w = uyvy.shape[0], uyvy.shape[1] // 2
    y = uyvy[:, 1::2]
    cb = cv2.resize(np.ascontiguousarray(uyvy[:, 0::4]), (w, h), interpolation=cv2.INTER_LINEAR)
    cr = cv2.resize(np.ascontiguousarray(uyvy[:, 2::4]), (w, h), interpolation=cv2.INTER_LINEAR)
    return cv2.transform(cv2.merge([np.ascontiguousarray(y), cb, cr]), BT709_UYVY)


def load_decklink_api():
    """Type library wrappers generated by comtypes from the installed Desktop Video driver."""
    if "comtypes" not in sys.modules:
        sys.coinit_flags = 0   # COINIT_MULTITHREADED: DeckLink calls back on its own threads
    import comtypes.client as cc
    return cc.GetModule(DECKLINK_TLB)


def list_decklink_devices(api) -> list:
    import comtypes.client as cc
    it = cc.CreateObject(api.CDeckLinkIterator, interface=api.IDeckLinkIterator)
    out = []
    while True:
        try:
            d = it.Next()
        except Exception:
            break
        if not d:
            break
        out.append((d.GetDisplayName(), d))
    return out


class DeckLinkSDKReader:
    def __init__(self, device: Optional[str] = None, mode: str = "bmdModeHD1080p5994",
                 deinterlace: str = "adaptive", keep_meta: int = 300, motion_threshold: int = 10,
                 max_fps: Optional[float] = None):
        import comtypes
        self.api = api = load_decklink_api()
        devs = list_decklink_devices(api)
        if not devs:
            raise RuntimeError("DeckLink 장치를 찾지 못했습니다 (Desktop Video 드라이버 확인)")
        dev_s = str(device if device is not None else "0")
        if dev_s.isdigit():
            self.name, dev = devs[int(dev_s)]
        else:
            match = [(n, d) for n, d in devs if dev_s.lower() in n.lower()]
            if not match:
                raise RuntimeError(f"DeckLink 장치 '{dev_s}' 없음: {[n for n, _ in devs]}")
            self.name, dev = match[0]
        self.deinterlace = deinterlace
        self.motion_threshold = int(motion_threshold)
        self._prev_gray = None    # adaptive deinterlace: last frame's luma, for motion
        self.keep_meta = int(keep_meta)
        self.q: queue.Queue = queue.Queue(maxsize=2)
        self.meta: OrderedDict[int, list] = OrderedDict()
        self.meta_lock = threading.Lock()
        self.returned = 0           # frames handed out by read(): index k of packets_for(k)
        self.dropped = 0
        self.no_signal = 0
        self.max_fps = float(max_fps) if max_fps else None
        self.keep_every = 1         # use every n-th frame (59.94p in, 29.97 processing: 2)
        self._arrived = 0
        self.fps = 30000 / 1001
        self.mode_id = None
        self.mode_name = "?"
        self.interlaced = False
        self.inp = dev.QueryInterface(api.IDeckLinkInput)
        reader = self

        class Callback(comtypes.COMObject):
            _com_interfaces_ = [api.IDeckLinkInputCallback]

            # ctypes AddRefs COM in-arguments itself; never AddRef here (it leaks every frame).
            def VideoInputFormatChanged(self, events, new_mode, flags):
                try:
                    # The driver also reports colorspace/field changes; restarting the stream for
                    # those makes it report again (endless restarts, half the frame rate).
                    if new_mode.GetDisplayMode() == reader.mode_id:
                        return 0
                    reader._set_mode(new_mode)
                    reader.inp.PauseStreams()
                    reader.inp.EnableVideoInput(new_mode.GetDisplayMode(), api.bmdFormat8BitYUV,
                                                api.bmdVideoInputEnableFormatDetection)
                    reader.inp.FlushStreams()
                    reader.inp.StartStreams()
                    print(f"[INFO] DeckLink SDK input format: {reader.mode_name}"
                          + (f" (every {reader.keep_every}th frame -> {reader.out_fps:.2f} fps)" if reader.keep_every > 1 else ""))
                except Exception as e:   # never let an exception reach the driver
                    print(f"[WARN] DeckLink format change: {e}")
                return 0

            def VideoInputFrameArrived(self, frame, audio):
                if frame:
                    try:
                        reader._on_frame(frame)
                    except Exception as e:
                        print(f"[WARN] DeckLink frame: {e}")
                return 0

        self._cb = Callback()
        self.inp.SetCallback(self._cb)
        self._set_mode(self.inp.GetDisplayMode(getattr(api, mode)))
        self.inp.EnableVideoInput(getattr(api, mode), api.bmdFormat8BitYUV, api.bmdVideoInputEnableFormatDetection)
        self.inp.StartStreams()
        print(f"[INFO] DeckLink SDK input: {self.name} (format detection on, deinterlace={deinterlace}"
              f"{f', max {self.max_fps:.2f} fps' if self.max_fps else ''})")

    def _set_mode(self, mode):
        self.mode_id = mode.GetDisplayMode()
        self.mode_name = mode.GetName()
        duration, scale = mode.GetFrameRate()
        self.fps = scale / duration if duration else self.fps
        self.interlaced = mode.GetFieldDominance() in (self.api.bmdLowerFieldFirst, self.api.bmdUpperFieldFirst)
        # Faster than the processing rate: skip frames before converting them (each kept frame
        # still carries its own lens packet, so zoom stays matched to the picture).
        self.keep_every = max(1, round(self.fps / self.max_fps)) if self.max_fps else 1

    @property
    def out_fps(self) -> float:
        return self.fps / self.keep_every

    def _on_frame(self, frame):
        api = self.api
        if frame.GetFlags() & api.bmdFrameHasNoInputSource:
            self.no_signal += 1
            return
        self._arrived += 1
        if self._arrived % self.keep_every:
            return
        if frame.GetPixelFormat() != api.bmdFormat8BitYUV:
            return
        w, h, rb = frame.GetWidth(), frame.GetHeight(), frame.GetRowBytes()
        buf = frame.QueryInterface(api.IDeckLinkVideoBuffer)
        buf.StartAccess(api.bmdBufferAccessRead)
        try:
            raw = np.ctypeslib.as_array((ctypes.c_uint8 * (rb * h)).from_address(buf.GetBytes())).reshape(h, rb)
            uyvy = raw[::2, :w * 2] if self.interlaced and self.deinterlace == "bob" else raw[:, :w * 2]
            bgr = uyvy_to_bgr709(uyvy)
        finally:
            buf.EndAccess(api.bmdBufferAccessRead)
        if bgr.shape[0] != h:
            bgr = cv2.resize(bgr, (w, h), interpolation=cv2.INTER_LINEAR)
        elif self.interlaced and self.deinterlace == "adaptive":
            bgr = self._deinterlace_adaptive(bgr)
        item = (bgr, self._read_packets(frame))
        if self.q.full():
            try:
                self.q.get_nowait()   # keep the newest: latency must not build up
                self.dropped += 1
            except queue.Empty:
                pass
        try:
            self.q.put_nowait(item)
        except queue.Full:
            self.dropped += 1

    def _deinterlace_adaptive(self, woven: np.ndarray) -> np.ndarray:
        """Keep the second field where nothing moved since the last frame (full vertical detail),
        replace it by the first field's line average where something moved (no combing)."""
        gray = cv2.cvtColor(woven, cv2.COLOR_BGR2GRAY)
        prev, self._prev_gray = self._prev_gray, gray
        top = woven[0::2]
        below = np.vstack([top[1:], top[-1:]])                     # first-field line under each odd line
        est = cv2.addWeighted(top, 0.5, below, 0.5, 0)              # odd lines rebuilt from the first field
        if prev is None or prev.shape != gray.shape:
            moving = np.ones(est.shape[:2], np.uint8)
        else:
            d = cv2.absdiff(gray, prev)
            moving = (np.maximum(d[0::2], d[1::2]) > self.motion_threshold).astype(np.uint8)
            moving = cv2.dilate(moving, np.ones((3, 9), np.uint8))   # cover motion edges (fields are 1/60 s apart)
        out = woven.copy()
        out[1::2] = np.where(moving[..., None] > 0, est, woven[1::2])
        return out

    def _read_packets(self, frame) -> list:
        import comtypes
        api, out = self.api, []
        try:
            it = frame.QueryInterface(api.IDeckLinkVideoFrameAncillaryPackets).GetPacketIterator()
        except comtypes.COMError:
            return out
        while True:
            try:
                p = it.Next()
            except comtypes.COMError:
                break
            if not p:
                break
            try:
                ptr, size = p.GetBytes(api.bmdAncillaryPacketFormatUInt8)
                data = ctypes.string_at(ptr, size) if ptr and size else b""
            except comtypes.COMError:
                data = b""
            out.append((int(p.GetDID()), int(p.GetSDID()), int(p.GetLineNumber()), data))
        return out

    # same interface as the ffmpeg readers (wrapped by _ThreadedGrabber)
    def isOpened(self):
        return True

    def read(self, timeout: float = 1.0):
        try:
            bgr, packets = self.q.get(timeout=timeout)
        except queue.Empty:
            return False, None
        with self.meta_lock:
            self.meta[self.returned] = packets
            while len(self.meta) > self.keep_meta:
                self.meta.popitem(last=False)
        self.returned += 1
        return True, bgr

    def packets_for(self, index) -> Optional[list]:
        """ANC packets of the frame read() returned as number `index` (None if unknown)."""
        if index is None:
            return None
        with self.meta_lock:
            return self.meta.get(int(index))

    def release(self):
        try:
            self.inp.StopStreams()
            self.inp.DisableVideoInput()
            self.inp.SetCallback(None)
        except Exception:
            pass
